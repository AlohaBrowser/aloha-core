"""ALOHA (model A remap index): generator of the straight-line R-field applier.

make_aar.generate_res_index emits res/xml/bromium_res_index.xml and returns a ResIndex; this module
turns the same ResIndex into com/alohamobile/bromium/BromiumResIndex.java, compiled by
make_aar.compile_extra_javas next to R.java. Runtime counterpart: BromiumResources.applyGenerated().
"""

import os
from pathlib import Path

from aloha_log import log


class ResIndex:
    """What generate_res_index emitted, in emission order. Consumed by generate_res_apply so the
    generated applier assigns R fields in exactly the order the XML lists them."""

    def __init__(self, types: list, indexed: list, fallback: list, phantom: list):
        self.types = types        # resource types in remap order (make_aar.res_index_types)
        self.indexed = indexed    # [(type, R field)] for <i> entries, XML order
        self.fallback = fallback  # [(type, R field)] for <f> entries, XML order
        self.phantom = phantom    # [(type, R field)] neither shipped nor read by code -> 0


# ALOHA (model A remap index, generated applier): emit
# com/alohamobile/bromium/BromiumResIndex.java — straight-line assignments of the R fields from
# an int[] that BromiumResources.init fills by a positional pass over bromium_res_index.xml.
#
# Why: the reflective remap (Class.forName + getDeclaredFields + Field.setInt over ~2450 fields,
# plus a name-keyed HashMap) is a one-shot method, so it never gets JIT-compiled and runs in the
# interpreter on every fresh install/update: measured 165 ms of a 227 ms remap on Redmi Note 7
# and ~70 ms of 77 ms on Galaxy S24 for the reflection pass alone; with this class the whole
# remap is ~65 ms / ~8 ms.
# ~2450 plain putstatic instructions cost a fraction of a millisecond in any execution mode —
# the same shape upstream uses in R.onResourcesLoaded.
#
# The XML and this class come from the same ResIndex in the same make_aar run, so the contract
# is purely positional: ids[k] is the k-th <i> entry, followed by the <f> entries in order.
# BromiumResources verifies INDEXED/FALLBACK against what it counted in the XML and falls back
# to the reflective path on any mismatch, so a skew can only cost speed, never correctness.
def generate_res_apply(index: ResIndex, java_src_dir: Path):
    out = java_src_dir / "com/alohamobile/bromium/BromiumResIndex.java"
    os.makedirs(out.parent, exist_ok=True)
    by_type = {t: [] for t in index.types}
    for k, (t, field) in enumerate(index.indexed):
        by_type[t].append((field, f"ids[{k}]"))
    base = len(index.indexed)
    for k, (t, field) in enumerate(index.fallback):
        by_type[t].append((field, f"ids[{base + k}]"))
    for t, field in index.phantom:
        by_type[t].append((field, "0"))

    with open(out, "w") as f:
        f.write("// Generated by aloha/build/res_apply.py (generate_res_apply). Do not edit.\n")
        f.write("package com.alohamobile.bromium;\n\n")
        f.write("/**\n * Assigns chromium's precompiled R fields from the ids bulk-read out of\n"
                " * res/xml/bromium_res_index.xml. Positional contract: ids[0..INDEXED) are the\n"
                " * &lt;i&gt; entries in document order, ids[INDEXED..INDEXED+FALLBACK) the &lt;f&gt;\n"
                " * entries. Fields backed by neither are set to 0 (phantom R entries).\n */\n")
        f.write("public final class BromiumResIndex {\n")
        f.write(f"    public static final int INDEXED = {len(index.indexed)};\n")
        f.write(f"    public static final int FALLBACK = {len(index.fallback)};\n")
        f.write(f"    public static final int PHANTOM = {len(index.phantom)};\n\n")
        f.write("    private BromiumResIndex() {}\n\n")
        f.write("    public static void apply(int[] ids) {\n")
        f.write("        if (ids.length != INDEXED + FALLBACK) {\n")
        f.write("            throw new IllegalArgumentException(\"ids.length \" + ids.length);\n")
        f.write("        }\n")
        for t in index.types:
            if by_type[t]:
                f.write(f"        apply_{t}(ids);\n")
        f.write("    }\n")
        for t in index.types:
            if not by_type[t]:
                continue
            f.write(f"\n    private static void apply_{t}(int[] ids) {{\n")
            for field, value in by_type[t]:
                f.write(f"        gen.base_module.R.{t}.{field} = {value};\n")
            f.write("    }\n")
        f.write("}\n")
    log(f"Resource applier: {out.name} — {len(index.indexed)} indexed, {len(index.fallback)} "
        f"fallback, {len(index.phantom)} phantom fields")
